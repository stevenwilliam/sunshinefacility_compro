"""Generate db/migrations/0002_seed_content.{up,down}.sql from content.py.

    python3 -I scripts/seed/gen_seed.py

Ids are deterministic UUIDv7s — a fixed timestamp plus a hash of each row's
natural key — so regenerating produces byte-identical SQL. That matters
because an applied migration is checksummed: a file that changes every time
it is generated would be refused at boot (platform/database).
"""

import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import content as C  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT_UP = os.path.join(ROOT, "db", "migrations", "0002_seed_content.up.sql")
OUT_DOWN = os.path.join(ROOT, "db", "migrations", "0002_seed_content.down.sql")

BASE_MS = 1792627200000  # 2026-10-22T00:00:00Z
_counter = [0]


def uid(natural_key: str) -> str:
    """UUIDv7 layout: 48-bit ms timestamp, version 7, variant 10, rest from a hash."""
    _counter[0] += 1
    ms = BASE_MS + _counter[0]
    h = hashlib.sha256(natural_key.encode()).digest()
    b = bytearray(16)
    b[0:6] = ms.to_bytes(6, "big")
    b[6] = 0x70 | (h[0] & 0x0F)
    b[7] = h[1]
    b[8] = 0x80 | (h[2] & 0x3F)
    b[9:16] = h[3:10]
    x = b.hex()
    return f"{x[0:8]}-{x[8:12]}-{x[12:16]}-{x[16:20]}-{x[20:32]}"


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = str(v)
    if "\x00" in s:
        raise ValueError("NUL in seed text")
    return "'" + s.replace("'", "''") + "'"


def media_ref(slug):
    return "NULL" if slug is None else f"(SELECT id FROM media WHERE slug = {q(slug)})"


out = []
emit = out.append

emit("-- 0002_seed_content — GENERATED by scripts/seed/gen_seed.py from scripts/seed/content.py.")
emit("-- Do not edit by hand. Every string comes from the approved design files, both languages.")
emit("-- Media rows are created here without bytes; `sfg seed-assets` uploads and processes the files.")
emit("")

# Media ---------------------------------------------------------------------
emit("-- Media library (files arrive with `sfg seed-assets`).")
for name, (alt_en, alt_id) in C.PHOTOS.items():
    slug = "photo/" + name
    emit(f"INSERT INTO media (id, slug, kind, name, alt_en, alt_id) VALUES ({q(uid(slug))}, {q(slug)}, 'photo', {q(name + '.png')}, {q(alt_en)}, {q(alt_id)});")
for slug_name, name, _ind in C.CLIENTS:
    slug = "logo/" + slug_name
    emit(f"INSERT INTO media (id, slug, kind, name, alt_en, alt_id) VALUES ({q(uid(slug))}, {q(slug)}, 'logo', {q(slug_name + '.png')}, {q(name)}, {q(name)});")
for f in C.CERT_FILES:
    slug = "certificate/" + f
    emit(f"INSERT INTO media (id, slug, kind, name) VALUES ({q(uid(slug))}, {q(slug)}, 'certificate', {q(f + '.png')});")
for key, (fname, alt_en, alt_id) in C.BRAND_FILES.items():
    slug = "brand/" + key
    emit(f"INSERT INTO media (id, slug, kind, name, alt_en, alt_id) VALUES ({q(uid(slug))}, {q(slug)}, 'brand', {q(fname)}, {q(alt_en)}, {q(alt_id)});")
emit("")

# Parameters ----------------------------------------------------------------
emit("-- Parameters (CLAUDE.md §8).")
for i, (grp, key, en, id_, desc, ph, secret) in enumerate(C.PARAMETERS):
    emit("INSERT INTO parameters (id, grp, key, value_en, value_id, description, is_secret, is_placeholder, sort) VALUES "
         f"({q(uid('param/' + grp + '/' + key))}, {q(grp)}, {q(key)}, {q(en)}, {q(id_)}, {q(desc)}, {q(secret)}, {q(ph)}, {i});")
emit("")

# Site text -----------------------------------------------------------------
emit("-- Site text (BR-1.1).")
for key, v in C.TEXT.items():
    en, id_ = v[0], v[1]
    ph = len(v) > 2 and v[2]
    emit(f"INSERT INTO site_text (key, value_en, value_id, is_placeholder) VALUES ({q(key)}, {q(en)}, {q(id_)}, {q(ph)});")
emit("")

# Page sections -------------------------------------------------------------
emit("-- Page sections.")
for i, (page, section, ten, tid, ben, bid, image, ph) in enumerate(C.SECTIONS):
    emit("INSERT INTO page_sections (id, page, section, title_en, title_id, body_en, body_id, image_id, is_placeholder, sort) VALUES "
         f"({q(uid('section/' + page + '/' + section))}, {q(page)}, {q(section)}, {q(ten)}, {q(tid)}, {q(ben)}, {q(bid)}, {media_ref(image)}, {q(ph)}, {i});")
emit("")

# Service lines -------------------------------------------------------------
emit("-- Business lines and their lists.")
for i, L in enumerate(C.LINES):
    k = L["key"]
    base, ink, shade, on_ink, label = L["colors"]
    emit("INSERT INTO service_lines (id, key, sort, title_en, title_id, short_en, short_id, label_en, label_id, "
         "summary_en, summary_id, description_en, description_id, lead_en, lead_id, "
         "color_base, color_ink, color_shade, color_on_ink, color_label, mark_id, photo_id, show_map, show_certs, map_image_id) VALUES "
         f"({q(uid('line/' + k))}, {q(k)}, {i + 1}, {q(L['title'][0])}, {q(L['title'][1])}, {q(L['short'][0])}, {q(L['short'][1])}, "
         f"{q(L['label'][0])}, {q(L['label'][1])}, {q(L['summary'][0])}, {q(L['summary'][1])}, "
         f"{q(L['description'][0])}, {q(L['description'][1])}, {q(L['lead'][0])}, {q(L['lead'][1])}, "
         f"{q(base)}, {q(ink)}, {q(shade)}, {q(on_ink)}, {q(label)}, {media_ref('brand/sg-' + k)}, {media_ref('photo/' + L['photo'])}, "
         f"{q(L.get('show_map', False))}, {q(L.get('show_certs', False))}, {media_ref('photo/supply-map') if L.get('show_map') else 'NULL'});")
    line = f"(SELECT id FROM service_lines WHERE key = {q(k)})"
    for kind, items in (("card_tag", L["card_tags"]), ("service_tag", L["service_tags"]), ("hero_point", L["hero_points"])):
        for j, (en, id_) in enumerate(items):
            emit(f"INSERT INTO service_items (id, line_id, kind, text_en, text_id, sort) VALUES ({q(uid('item/' + k + '/' + kind + '/' + str(j)))}, {line}, {q(kind)}, {q(en)}, {q(id_)}, {j});")
    for j, ((ven, vid), (len_, lid)) in enumerate(L["facts"]):
        emit(f"INSERT INTO service_facts (id, line_id, value_en, value_id, label_en, label_id, sort) VALUES ({q(uid('fact/' + k + '/' + str(j)))}, {line}, {q(ven)}, {q(vid)}, {q(len_)}, {q(lid)}, {j});")
    for j, ((ten, tid), body, items) in enumerate(L["groups"]):
        ben, bid = body if body else ("", "")
        ien, iid = ("\n".join(items[0]), "\n".join(items[1])) if items else ("", "")
        emit("INSERT INTO service_groups (id, line_id, title_en, title_id, body_en, body_id, items_en, items_id, sort) VALUES "
             f"({q(uid('group/' + k + '/' + str(j)))}, {line}, {q(ten)}, {q(tid)}, {q(ben)}, {q(bid)}, {q(ien)}, {q(iid)}, {j});")
emit("")

# Industries ----------------------------------------------------------------
emit("-- Industries, and which lines serve each (decision D12: one mapping for both pages).")
for i, (key, icon, (ten, tid), (ben, bid), lines) in enumerate(C.INDUSTRIES):
    emit(f"INSERT INTO industries (id, key, icon, title_en, title_id, body_en, body_id, sort) VALUES ({q(uid('industry/' + key))}, {q(key)}, {q(icon)}, {q(ten)}, {q(tid)}, {q(ben)}, {q(bid)}, {i + 1});")
    for j, ln in enumerate(lines):
        emit(f"INSERT INTO industry_lines (industry_id, line_id, sort) VALUES ((SELECT id FROM industries WHERE key = {q(key)}), (SELECT id FROM service_lines WHERE key = {q(ln)}), {j});")
emit("")

# Clients -------------------------------------------------------------------
emit("-- Clients, in trust-bar order.")
for i, (slug_name, name, ind) in enumerate(C.CLIENTS):
    emit(f"INSERT INTO clients (id, name, logo_id, industry_id, sort) VALUES ({q(uid('client/' + slug_name))}, {q(name)}, {media_ref('logo/' + slug_name)}, (SELECT id FROM industries WHERE key = {q(ind)}), {i + 1});")
emit("")

# Certificates --------------------------------------------------------------
emit("-- Certificates. Halal expired 2025-08-25: seeded unpublished (BR-3.5).")
for i, (name, issuer, valid, f, (den, did), pub) in enumerate(C.CERTIFICATES):
    emit("INSERT INTO certificates (id, name, issuer, valid_until, image_id, description_en, description_id, sort, published) VALUES "
         f"({q(uid('cert/' + f))}, {q(name)}, {q(issuer)}, {q(valid)}, {media_ref('certificate/' + f)}, {q(den)}, {q(did)}, {i + 1}, {q(pub)});")
emit("")

# Lists ---------------------------------------------------------------------
emit("-- Small lists (decision D11).")
for list_key, items in C.LISTS.items():
    for j, (icon, (ten, tid), (ben, bid), (men, mid), color, ph) in enumerate(items):
        emit("INSERT INTO content_items (id, list_key, icon, title_en, title_id, body_en, body_id, meta_en, meta_id, color, sort, is_placeholder) VALUES "
             f"({q(uid('list/' + list_key + '/' + str(j)))}, {q(list_key)}, {q(icon)}, {q(ten)}, {q(tid)}, {q(ben)}, {q(bid)}, {q(men)}, {q(mid)}, {q(color)}, {j + 1}, {q(ph)});")
emit("")

# Stats ---------------------------------------------------------------------
emit("-- Stats strips.")
for scope, rows in C.STATS.items():
    for j, ((ven, vid), (len_, lid)) in enumerate(rows):
        emit(f"INSERT INTO stats (id, scope, value_en, value_id, label_en, label_id, sort) VALUES ({q(uid('stat/' + scope + '/' + str(j)))}, {q(scope)}, {q(ven)}, {q(vid)}, {q(len_)}, {q(lid)}, {j + 1});")
emit("")

# Careers -------------------------------------------------------------------
emit("-- Sample openings: placeholders (BR-2.1).")
for i, (line, loc, typ, (ten, tid), (sen, sid), (ren, rid)) in enumerate(C.OPENINGS):
    emit("INSERT INTO career_openings (id, title_en, title_id, line_id, location_key, type_key, closing_date, summary_en, summary_id, requirements_en, requirements_id, sort, is_placeholder) VALUES "
         f"({q(uid('opening/' + str(i)))}, {q(ten)}, {q(tid)}, (SELECT id FROM service_lines WHERE key = {q(line)}), {q(loc)}, {q(typ)}, {q(C.OPENING_CLOSING)}, "
         f"{q(sen)}, {q(sid)}, {q(chr(10).join(ren))}, {q(chr(10).join(rid))}, {i + 1}, true);")
emit("")

emit("-- Testimonials: placeholders, unpublished (BR-2.4).")
for i, ((qen, qid), name, role, company) in enumerate(C.TESTIMONIALS):
    emit("INSERT INTO testimonials (id, quote_en, quote_id, name, role, company, sort, published, is_placeholder) VALUES "
         f"({q(uid('testimonial/' + str(i)))}, {q(qen)}, {q(qid)}, {q(name)}, {q(role)}, {q(company)}, {i + 1}, false, true);")
emit("")

emit("-- Management: placeholders.")
for i, (name, (ren, rid)) in enumerate(C.MANAGEMENT):
    emit(f"INSERT INTO management (id, name, role_en, role_id, sort, is_placeholder) VALUES ({q(uid('mgmt/' + str(i)))}, {q(name)}, {q(ren)}, {q(rid)}, {i + 1}, true);")

with open(OUT_UP, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")

