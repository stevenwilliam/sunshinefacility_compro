// Generates src/lib/phosphor.tsx: the Phosphor icons this app imports, with
// only the two weights it uses (regular, fill). The upstream components carry
// all six weights (~2.5 kB each); with ~80 icons that was ~170 kB of the
// first page's JavaScript.
//
//   node scripts/gen-icons.mjs        (run from web/, after npm ci)
//
// It scans src/ for `from '@/lib/phosphor'` imports, reads each icon's path
// data from node_modules/@phosphor-icons/react/dist/defs, and writes the file.
// A missing icon is an error, not a silent skip.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'src'
const DEFS = 'node_modules/@phosphor-icons/react/dist/defs'
const OUT = 'src/lib/phosphor.tsx'

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (/\.(tsx?|jsx?)$/.test(f) && p !== OUT) out.push(p)
  }
  return out
}

const names = new Set()
for (const f of walk(SRC)) {
  const s = readFileSync(f, 'utf8')
  for (const m of s.matchAll(/import\s*(?:type\s*)?\{([^}]+)\}\s*from\s*['"]@\/lib\/phosphor['"]/g)) {
    for (const n of m[1].split(',').map((x) => x.trim()).filter(Boolean)) {
      if (n === 'IconProps' || n.startsWith('type ')) continue
      names.add(n)
    }
  }
}

function weights(name) {
  const src = readFileSync(join(DEFS, `${name}.es.js`), 'utf8')
  const out = {}
  for (const w of ['regular', 'fill']) {
    const i = src.indexOf(`"${w}"`)
    if (i < 0) throw new Error(`${name}: no ${w} weight`)
    const end = src.indexOf('\n  ]', i)
    const chunk = src.slice(i, end)
    const paths = []
    for (const m of chunk.matchAll(/createElement\("(path|circle|rect|line|polyline|polygon|ellipse)",\s*(\{[^}]*\})/g)) {
      // eslint-disable-next-line no-new-func
      const attrs = Function(`return (${m[2]})`)()
      paths.push([m[1], attrs])
    }
    if (paths.length === 0) throw new Error(`${name}: no shapes for ${w}`)
    out[w] = paths
  }
  return out
}

const sorted = [...names].sort()
let body = `// GENERATED by scripts/gen-icons.mjs — do not edit. Phosphor Icons (MIT).
// Only the regular and fill weights of the icons this app imports.
import type { CSSProperties, SVGProps } from 'react'

type Shape = [string, Record<string, string>]
export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'weight'> {
  weight?: 'regular' | 'fill'
  size?: number | string
  style?: CSSProperties
}

function make(name: string, regular: Shape[], fill: Shape[]) {
  const C = ({ weight = 'regular', size = '1em', ...rest }: IconProps) => (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} fill="currentColor" viewBox="0 0 256 256" {...rest}>
      {(weight === 'fill' ? fill : regular).map(([tag, a], i) => {
        const T = tag as 'path'
        return <T key={i} {...a} />
      })}
    </svg>
  )
  C.displayName = name
  return C
}

`
for (const n of sorted) {
  const w = weights(n)
  body += `export const ${n} = make('${n}', ${JSON.stringify(w.regular)}, ${JSON.stringify(w.fill)})\n`
}
writeFileSync(OUT, body)
console.log(`wrote ${OUT}: ${sorted.length} icons`)
